const ALL = ['arm', 'scara', 'delta', 'cartesian'];
export const FORMATS = [
  { id: 'csv', group: 'neutral', name: 'Path list (CSV)', ext: 'csv', mime: 'text/csv', types: ALL, always: true },
  { id: 'json', group: 'neutral', name: 'Path list (JSON)', ext: 'json', mime: 'application/json', types: ALL, always: true },
  { id: 'urdf', group: 'open', name: 'ROS URDF (robot model)', ext: 'urdf', mime: 'application/xml', types: ['arm', 'scara', 'cartesian'] },
  { id: 'trajectory', group: 'open', name: 'ROS joint trajectory (JSON)', ext: 'trajectory.json', mime: 'application/json', types: ALL },
  ...VENDORS.map((v) => ({ id: v.id, group: 'vendor', name: v.name, ext: v.ext, mime: 'text/plain', types: v.types, vendor: true })),
];
export const formatById = (id) => FORMATS.find((f) => f.id === id) || null;
export const DEFAULT_SELECTION = ['csv', 'json'];
export const cleanSelection = (list) => {
  const out = new Set(['csv', 'json']);
  if (Array.isArray(list)) for (const id of list) if (typeof id === 'string' && formatById(id)) out.add(id);
  return FORMATS.map((f) => f.id).filter((id) => out.has(id));
};

const OMIT = {
  urdf: [], trajectory: ['out', 'waitin', 'wait'],
};
/** Export one format. Refusals say what this format cannot express (code + detail) and write no file. */
export function exportOne(id, run, cell, opts = {}) {
  const f = formatById(id), r = cell.robot;
  if (!f) return { ok: false, id, refused: { code: 'unknown-format' } };
  if (!run || !run.ok) return { ok: false, id, refused: { code: 'no-run' } };
  if (!f.types.includes(r.type)) return { ok: false, id, refused: { code: 'robot-type', type: r.type } };
  const file = (text) => ({ name: `${baseName(cell)}.${f.ext}`, text, mime: f.mime });
  if (id === 'csv') return { ok: true, id, file: file(neutralCsv(run, cell)), omitted: [] };
  if (id === 'json') return { ok: true, id, file: file(neutralJson(run, cell, opts)), omitted: [] };
  if (id === 'urdf') return { ok: true, id, file: file(urdfText(run, cell)), omitted: ['program'] };
  if (id === 'trajectory') {
    const ops = new Set(run.steps.filter((s) => s.op === 'out' || s.op === 'waitin' || s.op === 'grip' || s.op === 'release').map((s) => 'signal'));
    return { ok: true, id, file: file(trajectoryJson(run, cell)), omitted: [...ops] };
  }
  const v = VENDORS.find((x) => x.id === id);
  const res = v.write(buildPlan(run, cell), cell, { gripOut: cell.gripOut || 1, ...opts, generatedBy: GENERATED_BY });
  if (!res.ok) return { ok: false, id, refused: res.refused };
  return { ok: true, id, file: file(res.text), omitted: res.omitted || [] };
}
export function exportMany(ids, run, cell, opts = {}) { return cleanSelection(ids).map((id) => exportOne(id, run, cell, opts)); }
