/**
 * robot-formats.js — the robot program formats a person can choose in the Robot cell panel (0.9 SU.1128, owner 2026-11-06:
 * "allow the user to select robot formats"). DOM-free. Each format turns a finished run (lib/robot.js runProgram) into one text file.
 *
 *   neutral   csv, json   always written: the path list (steps, tool point, joint values, seconds, speed, signals)
 *   open      urdf        ROS URDF of the robot (links, joints, limits from the table), tree robots only
 *             trajectory  ROS joint trajectory (JointTrajectory message as JSON) from the run
 *   vendor    see lib/robot-vendors.js: only languages whose basic statements two public sources confirm (lib/robot-sources.js)
 *
 *   FORMATS                          the list (id, kind, name, ext, types it can express)
 *   exportOne(id, run, cell, opts)   { ok, file: { name, text, mime }, omitted: [...], refused: { code, ... } }
 *   exportMany(ids, run, cell, opts) one result per id (csv and json are added when missing)
 *   buildPlan(run, cell)             the steps as the plain motion / signal list the vendor writers share
 *
 * Every vendor program starts with the line "Generated by CadCraft; simulate and verify on your robot controller before running;
 * not endorsed by the vendor" in that language's comment syntax. Nothing here claims a program was run on a robot.
 */
import { D2R, jointLimits, isSlide, nDof, fkArmBase, toBase, pathCsv } from './robot.js';
import { VENDORS } from './robot-vendors.js';

export const GENERATED_BY = 'Generated by CadCraft; simulate and verify on your robot controller before running; not endorsed by the vendor';
const fmtNum = (v) => { if (!Number.isFinite(v)) return '0'; if (Math.abs(v) < 1e-12) return '0'; return String(+v.toPrecision(15)); };
export const num15 = fmtNum;
const xml = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const safe = (s, def) => (String(s || '').replace(/[^A-Za-z0-9_]/g, '_').replace(/^([^A-Za-z])/, 'r_$1') || def);

// ------------------------------------------------------------------------------------------------ rotations (3x3 row-major arrays of 9)
export const rotOf = (T) => [T[0], T[1], T[2], T[4], T[5], T[6], T[8], T[9], T[10]];
/** Roll, pitch, yaw with R = Rz(yaw) Ry(pitch) Rx(roll) (the URDF and ROS convention). */
export function rpyOf(R) {
  const p = Math.asin(Math.max(-1, Math.min(1, -R[6])));
  if (Math.abs(R[6]) > 1 - 1e-9) return [0, p, Math.atan2(-R[1], R[4])];
  return [Math.atan2(R[7], R[8]), p, Math.atan2(R[3], R[0])];
}
/** Rotation vector (axis times angle, radians). */
export function rotvecOf(R) {
  const tr = R[0] + R[4] + R[8], c = Math.max(-1, Math.min(1, (tr - 1) / 2)), ang = Math.acos(c);
  if (ang < 1e-9) return [0, 0, 0];
  let ax;
  if (Math.PI - ang < 1e-6) {                        // near 180 degrees: take the axis from the diagonal
    const x = Math.sqrt(Math.max(0, (R[0] + 1) / 2)), y = Math.sqrt(Math.max(0, (R[4] + 1) / 2)), z = Math.sqrt(Math.max(0, (R[8] + 1) / 2));
    const big = Math.max(x, y, z);
    if (big === x) ax = [x, Math.sign(R[1] + R[3] || 1) * y, Math.sign(R[2] + R[6] || 1) * z];
    else if (big === y) ax = [Math.sign(R[1] + R[3] || 1) * x, y, Math.sign(R[5] + R[7] || 1) * z];
    else ax = [Math.sign(R[2] + R[6] || 1) * x, Math.sign(R[5] + R[7] || 1) * y, z];
    const n = Math.hypot(...ax); ax = ax.map((v) => v / n);
  } else {
    ax = [R[7] - R[5], R[2] - R[6], R[3] - R[1]]; const n = Math.hypot(...ax); ax = ax.map((v) => v / n);
  }
  return ax.map((v) => v * ang);
}
export function rotFromVec(v) {
  const a = Math.hypot(...v); if (a < 1e-12) return [1, 0, 0, 0, 1, 0, 0, 0, 1];
  const [x, y, z] = v.map((c) => c / a), c = Math.cos(a), s = Math.sin(a), t = 1 - c;
  return [t * x * x + c, t * x * y - s * z, t * x * z + s * y, t * x * y + s * z, t * y * y + c, t * y * z - s * x, t * x * z - s * y, t * y * z + s * x, t * z * z + c];
}
/** Unit quaternion [w, x, y, z] (w >= 0). */
export function quatOf(R) {
  const tr = R[0] + R[4] + R[8]; let w, x, y, z;
  if (tr > 0) { const s = Math.sqrt(tr + 1) * 2; w = s / 4; x = (R[7] - R[5]) / s; y = (R[2] - R[6]) / s; z = (R[3] - R[1]) / s; }
  else if (R[0] > R[4] && R[0] > R[8]) { const s = Math.sqrt(1 + R[0] - R[4] - R[8]) * 2; w = (R[7] - R[5]) / s; x = s / 4; y = (R[1] + R[3]) / s; z = (R[2] + R[6]) / s; }
  else if (R[4] > R[8]) { const s = Math.sqrt(1 + R[4] - R[0] - R[8]) * 2; w = (R[2] - R[6]) / s; x = (R[1] + R[3]) / s; y = s / 4; z = (R[5] + R[7]) / s; }
  else { const s = Math.sqrt(1 + R[8] - R[0] - R[4]) * 2; w = (R[3] - R[1]) / s; x = (R[2] + R[6]) / s; y = (R[5] + R[7]) / s; z = s / 4; }
  const n = Math.hypot(w, x, y, z), q = [w / n, x / n, y / n, z / n];
  return q[0] < 0 ? q.map((v) => -v) : q;
}
/** Euler angles A (about z), B (about y), C (about x), degrees: R = Rz(A) Ry(B) Rx(C) (same chain as rpyOf, yaw-pitch-roll). */
export function abcOf(R) { const [r, p, y] = rpyOf(R); return [y / D2R, p / D2R, r / D2R]; }

// ------------------------------------------------------------------------------------------------ the plan the vendor writers share
/**
 * One entry per thing a controller does, in order. k: 'J' joint move, 'L' straight move, 'out', 'waitin', 'wait'.
 * Moves carry q (joint values, radians or metres), pose (tool point in the robot base frame, metres, and R = 3x3 rotation of the
 * tool frame in the base frame), pct (speed percent) and the target label.
 */
export function buildPlan(run, cell) {
  const r = cell.robot, out = [];
  for (const s of run.steps) {
    if (s.op === 'movej' || s.op === 'movel') {
      const e = { k: s.op === 'movej' ? 'J' : 'L', q: s.q.slice(), pct: s.pct, label: s.target, t: s.t, line: s.line };
      if (r.type === 'arm') { const f = fkArmBase(r, s.q); e.pose = f.tool; e.R = rotOf(f.T); }
      else if (s.p) { e.pose = toBase(r, s.p); }
      out.push(e);
    } else if (s.op === 'grip' || s.op === 'release') {
      out.push({ k: 'out', n: s.io.n, on: s.io.on, label: s.op, line: s.line });
      if (s.t > 0) out.push({ k: 'wait', s: s.t, label: s.op, line: s.line });
    } else if (s.op === 'out' || s.op === 'waitin') out.push({ k: s.op, n: s.io.n, on: s.io.on, line: s.line });
    else if (s.op === 'wait') out.push({ k: 'wait', s: s.t, line: s.line });
  }
  return out;
}
export const jointNames = (r) => (r.type === 'delta' ? ['arm_1', 'arm_2', 'arm_3'] : r.type === 'cartesian' ? ['axis_x', 'axis_y', 'axis_z', 'tool_yaw'] : r.type === 'scara' ? ['joint_1', 'joint_2', 'slide_z', 'tool_yaw'] : r.joints.map((_, i) => 'joint_' + (i + 1)));

// ------------------------------------------------------------------------------------------------ neutral: CSV and JSON
const baseName = (cell) => safe(cell.robot.id, 'robot').toLowerCase();
function neutralJson(run, cell, opts) {
  const r = cell.robot, names = jointNames(r);
  const steps = run.steps.map((s, i) => ({
    step: i + 1, line: s.line, op: s.op, target: s.target, speed_percent: s.pct,
    tool_point_m: s.p ? s.p.map((v) => +v.toPrecision(15)) : null,
    joints: s.q ? s.q.map((v, j) => +(isSlide(r, j) ? v : v / D2R).toPrecision(15)) : null,
    seconds: s.t, cumulative_seconds: s.tcum, signal: s.io ? { number: s.io.n, on: s.io.on } : null,
  }));
  return JSON.stringify({
    format: 'cadcraft-robot-path', version: 1, generated_by: GENERATED_BY,
    robot: { id: r.id, type: r.type, name: r.name, base_world_m: [r.x, r.y, r.z], base_rotation_deg: r.rot, joint_names: names, joint_units: names.map((_, j) => (isSlide(r, j) ? 'm' : 'deg')) },
    units: { length: 'm', time: 's' }, cycle_seconds: run.cycle, steps,
  }, null, 2) + '\n';
}
function neutralCsv(run, cell) {
  const r = cell.robot, names = jointNames(r);
  const head = ['step', 'line', 'op', 'target', 'x_m', 'y_m', 'z_m', 'speed_percent', 'seconds', 'cumulative_seconds', 'signal', 'signal_on', ...names.map((n, j) => n + (isSlide(r, j) ? '_m' : '_deg'))];
  const rows = [head];
  run.steps.forEach((s, i) => rows.push([i + 1, s.line, s.op, s.target, ...(s.p ? s.p.map((v) => +v.toPrecision(15)) : ['', '', '']), s.pct, s.t, s.tcum, s.io ? s.io.n : '', s.io ? (s.io.on ? 1 : 0) : '',
    ...names.map((_, j) => (s.q ? +(isSlide(r, j) ? s.q[j] : s.q[j] / D2R).toPrecision(15) : ''))]));
  return rows.map((x) => x.join(',')).join('\n') + '\n';
}

// ------------------------------------------------------------------------------------------------ URDF (ROS)
const I3 = [1, 0, 0, 0, 1, 0, 0, 0, 1];
const mm3 = (A, B) => { const C = new Array(9).fill(0); for (let i = 0; i < 3; i++) for (let j = 0; j < 3; j++) for (let k = 0; k < 3; k++) C[i * 3 + j] += A[i * 3 + k] * B[k * 3 + j]; return C; };
const rx3 = (a) => [1, 0, 0, 0, Math.cos(a), -Math.sin(a), 0, Math.sin(a), Math.cos(a)];
const rz3 = (a) => [Math.cos(a), -Math.sin(a), 0, Math.sin(a), Math.cos(a), 0, 0, 0, 1];
const mv3 = (R, v) => [R[0] * v[0] + R[1] * v[1] + R[2] * v[2], R[3] * v[0] + R[4] * v[1] + R[5] * v[2], R[6] * v[0] + R[7] * v[1] + R[8] * v[2]];
/** A pose (R, p) composed with a pose: (R1,p1)*(R2,p2). */
const pose = (R, p) => ({ R, p });
const compose = (A, B) => pose(mm3(A.R, B.R), mv3(A.R, B.p).map((v, i) => v + A.p[i]));
const originOf = (P) => { const rpy = rpyOf(P.R); return `<origin xyz="${P.p.map(fmtNum).join(' ')}" rpy="${rpy.map(fmtNum).join(' ')}"/>`; };

function urdfText(run, cell) {
  const r = cell.robot, name = safe(r.id, 'robot') ;
  const L = [];
  const lim = jointLimits(r);
  const joint = (n, type, parent, child, P, axis, i) => {
    L.push(`  <joint name="${n}" type="${type}">`, `    <parent link="${parent}"/>`, `    <child link="${child}"/>`, '    ' + originOf(P));
    if (axis) L.push(`    <axis xyz="${axis}"/>`);
    if (i !== undefined) {
      const va = r.type === 'arm' ? r.joints[i].vmax * D2R : (isSlide(r, i) ? r.vmax[i] : r.vmax[i] * D2R);
      L.push(`    <limit lower="${fmtNum(lim[i][0])}" upper="${fmtNum(lim[i][1])}" effort="0" velocity="${fmtNum(va)}"/>`);
    }
    L.push('  </joint>');
  };
  L.push('<?xml version="1.0"?>', `<!-- ${GENERATED_BY}. -->`,
    '<!-- Kinematic skeleton only: no meshes, masses or inertias. effort="0" is a placeholder (URDF requires the attribute; CadCraft does not model joint torque). -->',
    `<!-- Units: metres and radians; revolute limits in radians, prismatic limits in metres. Robot base placed in the layout at x ${fmtNum(r.x)} y ${fmtNum(r.y)} z ${fmtNum(r.z)} m, turned ${fmtNum(r.rot)} deg (the world joint). -->`,
    `<robot name="${xml(name)}">`, '  <link name="world"/>', '  <link name="base_link"/>');
  joint('world_to_base', 'fixed', 'world', 'base_link', pose(rz3(r.rot * D2R), [r.x, r.y, r.z]));
  const links = [];
  if (r.type === 'arm') {
    let F = pose(I3, [0, 0, 0]);
    r.joints.forEach((j, i) => {
      const o = compose(F, pose(rz3(j.offset * D2R), [0, 0, 0]));
      links.push('link_' + (i + 1));
      joint('joint_' + (i + 1), 'revolute', i ? 'link_' + i : 'base_link', 'link_' + (i + 1), o, '0 0 1', i);
      F = pose(mm3(rx3(j.alpha * D2R), I3), [j.a, 0, j.d]);                   // Tz(d) Tx(a) Rx(alpha): translation (a, 0, d), rotation Rx(alpha)
    });
    links.push('flange'); joint('flange_fixed', 'fixed', 'link_' + r.joints.length, 'flange', F);
    links.push('tool0'); joint('tool0_fixed', 'fixed', 'flange', 'tool0', pose(I3, [0, 0, r.tool]));
  } else if (r.type === 'scara') {
    links.push('link_1', 'link_2', 'slide', 'tool_holder', 'tool0');
    joint('joint_1', 'revolute', 'base_link', 'link_1', pose(I3, [0, 0, 0]), '0 0 1', 0);
    joint('joint_2', 'revolute', 'link_1', 'link_2', pose(I3, [r.l1, 0, 0]), '0 0 1', 1);
    joint('slide_z', 'prismatic', 'link_2', 'slide', pose(I3, [r.l2, 0, 0]), '0 0 1', 2);
    joint('tool_yaw', 'revolute', 'slide', 'tool_holder', pose(I3, [0, 0, 0]), '0 0 1', 3);
    joint('tool0_fixed', 'fixed', 'tool_holder', 'tool0', pose(I3, [0, 0, -r.tool]));
  } else {                                                                      // cartesian
    links.push('carriage_x', 'carriage_y', 'slide', 'tool_holder', 'tool0');
    joint('axis_x', 'prismatic', 'base_link', 'carriage_x', pose(I3, [0, 0, 0]), '1 0 0', 0);
    joint('axis_y', 'prismatic', 'carriage_x', 'carriage_y', pose(I3, [0, 0, 0]), '0 1 0', 1);
    joint('axis_z', 'prismatic', 'carriage_y', 'slide', pose(I3, [0, 0, 0]), '0 0 1', 2);
    joint('tool_yaw', 'revolute', 'slide', 'tool_holder', pose(I3, [0, 0, 0]), '0 0 1', 3);
    joint('tool0_fixed', 'fixed', 'tool_holder', 'tool0', pose(I3, [0, 0, -r.tool]));
  }
  const body = L.join('\n');
  // links go first in a URDF by convention; joints may come in any order. Insert the remaining links before the first joint.
  const idx = body.indexOf('  <joint name="world_to_base"');
  return body.slice(0, idx) + links.map((n) => `  <link name="${n}"/>`).join('\n') + '\n' + body.slice(idx) + '\n</robot>\n';
}

// ------------------------------------------------------------------------------------------------ ROS joint trajectory
/**
 * trajectory_msgs/JointTrajectory as JSON: joint_names, then one point per sampled move end (straight moves every ~1 cm) with
 * positions (radians; metres for slides) and time_from_start. Velocities and accelerations are left empty (the message allows it);
 * a trajectory controller interpolates. Signals are not part of the message (reported as omitted).
 */
function trajectoryJson(run, cell) {
  const r = cell.robot, pts = [];
  let t0 = 0, last = r.home.slice();
  const push = (q, t) => { pts.push({ positions: q.map((v) => +v.toPrecision(15)), velocities: [], accelerations: [], effort: [], time_from_start: { sec: Math.floor(t + 1e-12), nanosec: Math.round((t - Math.floor(t + 1e-12)) * 1e9) % 1e9 } }); last = q; };
  push(last, 0);
  for (const s of run.steps) {
    const t1 = s.tcum;
    if ((s.op === 'movej' || s.op === 'movel') && s.q) {
      const qs = s.qs && s.qs.length ? s.qs : [s.q];
      qs.forEach((q, i) => push(q, t0 + (s.t * (i + 1)) / qs.length));
    } else if (s.t > 0) push(last, t1);
    t0 = t1;
  }
  return JSON.stringify({ header: { stamp: { sec: 0, nanosec: 0 }, frame_id: 'base_link' }, joint_names: jointNames(r), points: pts }, null, 2) + '\n';
}

