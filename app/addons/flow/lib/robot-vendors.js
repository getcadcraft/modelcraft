/**
 * robot-vendors.js — program writers for robot makers' languages (0.9 SU.1128). DOM-free.
 * A language is here ONLY when the statements it emits are confirmed by two independent public sources read on the date in
 * lib/robot-sources.js (URL + date there and in the panel's Sources list). Each writer emits a minimal, unverified program:
 * joint and straight moves, speed, signal set / wait, wait time, pick and place as signal + wait; no tool or frame statements
 * unless two sources confirm them (the header comment tells the person what to set on the controller instead).
 * Every program starts with the line  Generated by CadCraft; simulate and verify ... not endorsed by the vendor  in the language's
 * comment syntax. Nothing here claims a program was run on a robot.
 *
 * VENDORS: [{ id, name, ext, types, write(plan, cell, opts) -> { ok, text, omitted } | { ok: false, refused: { code, ... } } }]
 * plan: see buildPlan in robot-formats.js (entries k: 'J' | 'L' | 'out' | 'waitin' | 'wait').
 */
import { D2R, R2D } from './robot.js';

const n15 = (v) => { if (!Number.isFinite(v) || Math.abs(v) < 1e-12) return '0'; return String(+v.toPrecision(15)); };
// rotation helpers are small copies of the ones in robot-formats.js (that file imports this one, so it cannot be imported here)
function rotvec(R) {                       // through the unit quaternion: stable for turns near 180 degrees
  const tr = R[0] + R[4] + R[8]; let w, x, y, z;
  if (tr > 0) { const k = Math.sqrt(tr + 1) * 2; w = k / 4; x = (R[7] - R[5]) / k; y = (R[2] - R[6]) / k; z = (R[3] - R[1]) / k; }
  else if (R[0] > R[4] && R[0] > R[8]) { const k = Math.sqrt(1 + R[0] - R[4] - R[8]) * 2; w = (R[7] - R[5]) / k; x = k / 4; y = (R[1] + R[3]) / k; z = (R[2] + R[6]) / k; }
  else if (R[4] > R[8]) { const k = Math.sqrt(1 + R[4] - R[0] - R[8]) * 2; w = (R[2] - R[6]) / k; x = (R[1] + R[3]) / k; y = k / 4; z = (R[5] + R[7]) / k; }
  else { const k = Math.sqrt(1 + R[8] - R[0] - R[4]) * 2; w = (R[3] - R[1]) / k; x = (R[2] + R[6]) / k; y = (R[5] + R[7]) / k; z = k / 4; }
  const v = Math.hypot(x, y, z); if (v < 1e-14) return [0, 0, 0];
  let ang = 2 * Math.atan2(v, w); if (ang > Math.PI) ang -= 2 * Math.PI;
  return [x / v * ang, y / v * ang, z / v * ang];
}
const refuse = (code, extra = {}) => ({ ok: false, refused: { code, ...extra } });
const sixAxis = (cell) => cell.robot.type === 'arm' && cell.robot.joints.length === 6;

// ------------------------------------------------------------------------------------------------ Universal Robots URScript
/**
 * URScript, E-Series script manual 5.11 plus an independent community tutorial (lib/robot-sources.js: urscript).
 * Statements used: def name(): ... end; movej(q, a=, v=); movel(p[x,y,z,rx,ry,rz], a=, v=); set_digital_out(n, b);
 * while (get_standard_digital_in(n) != True): sync() end; sleep(t); # comments.
 */
const urscript = {
  id: 'urscript', name: 'Universal Robots URScript', ext: 'script', types: ['arm'],
  write(plan, cell, opts) {
    const r = cell.robot;
    if (!sixAxis(cell)) return refuse('six-axes');
    for (const e of plan) if ((e.k === 'out' || e.k === 'waitin') && (e.n < 0 || e.n > 9)) return refuse('signal-range', { n: e.n, max: 9 });
    const vJ = Math.max(...r.joints.map((j) => j.vmax)) * D2R, aJ = Math.max(...r.joints.map((j) => j.amax)) * D2R;
    const L = [
      `# ${opts.generatedBy}`,
      `# Format: URScript (UR E-Series script manual 5.11 and a community tutorial; see the Sources list in the panel).`,
      `# Robot model: ${r.name || r.type}. Joint values in movej are radians of THIS model's joint table; they are right for your robot only if its joint zero positions match.`,
      `# Poses in movel are the tool point in the model's base frame (metres, rotation vector in radians). Check the base frame of your robot (it may be turned against this model).`,
      `# Set the tool centre point on the controller to x 0, y 0, z ${n15(r.tool)} m (this program does not set a TCP). Moves stop at every point (no blending).`,
      `# Speeds: joint moves use the leading-axis limits of the table scaled by the speed percent; straight moves use ${n15(r.tcpV)} m/s and ${n15(r.tcpA)} m/s2 scaled the same way.`,
      'def cadcraft_cell():',
    ];
    let moves = 0;
    for (const e of plan) {
      const k = Math.min(1, Math.max(0.01, (e.pct || 100) / 100));
      if (e.k === 'J') { L.push(`  movej([${e.q.map(n15).join(', ')}], a=${n15(aJ * k)}, v=${n15(vJ * k)})  # ${e.label || ''}`.trimEnd()); moves++; }
      else if (e.k === 'L') { L.push(`  movel(p[${[...e.pose, ...rotvec(e.R)].map(n15).join(', ')}], a=${n15(r.tcpA * k)}, v=${n15(r.tcpV * k)})  # ${e.label || ''}`.trimEnd()); moves++; }
      else if (e.k === 'out') L.push(`  set_digital_out(${e.n}, ${e.on ? 'True' : 'False'})`);
      else if (e.k === 'waitin') L.push(`  while (get_standard_digital_in(${e.n}) != ${e.on ? 'True' : 'False'}):`, '    sync()', '  end');
      else if (e.k === 'wait') L.push(`  sleep(${n15(e.s)})`);
    }
    if (!moves && !plan.length) L.push('  sleep(0)');
    L.push('end', '');
    return { ok: true, text: L.join('\n'), omitted: ['tool', 'frame', 'blend'] };
  },
};

export const VENDORS = [urscript];
void R2D;
